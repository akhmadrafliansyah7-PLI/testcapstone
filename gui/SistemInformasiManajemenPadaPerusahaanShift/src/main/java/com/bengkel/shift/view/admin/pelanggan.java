    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        try {
            Pelanggan p = new Pelanggan();

            p.setNamaPelanggan(namaField.getText().trim());
            p.setNoHp(teleponField.getText().trim());

            if (controller.tambah(p)) {

                JOptionPane.showMessageDialog(this,
                        "Pelanggan berhasil ditambahkan!");

                muatTabel();

                namaField.setText("");
                teleponField.setText("");

            } else {
                JOptionPane.showMessageDialog(this,
                        "Gagal menambahkan pelanggan karena terjadi kesalahan database.");
            }

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(this,
                    e.getMessage(),
                    "Validasi Input",
                    JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnTambahActionPerformed
    
private void muatTabel() {

    DefaultTableModel model =
            (DefaultTableModel) jTable1.getModel();

    model.setRowCount(0);

    for (Pelanggan p : controller.tampilSemua()) {
        model.addRow(new Object[]{
            p.getIdPelanggan(),
            p.getNamaPelanggan(),
            p.getNoHp()
        });
    }
}

private void pilihData() {

    int baris = jTable1.getSelectedRow();

    if (baris != -1) {
        namaField.setText(
                jTable1.getValueAt(baris, 1).toString());

        teleponField.setText(
                jTable1.getValueAt(baris, 2).toString());
    }
}

private void ubahPelanggan() {

     int baris = jTable1.getSelectedRow();

    if (baris == -1) {
        JOptionPane.showMessageDialog(this,
                "Pilih pelanggan terlebih dahulu!");
        return;
    }

    try {
        Pelanggan p = new Pelanggan();

        p.setIdPelanggan(
                Integer.parseInt(
                        jTable1.getValueAt(baris, 0).toString()));

        p.setNamaPelanggan(namaField.getText().trim());
        p.setNoHp(teleponField.getText().trim());

        if (controller.ubah(p)) {

            JOptionPane.showMessageDialog(this,
                    "Data pelanggan berhasil diubah!");

            muatTabel();

            namaField.setText("");
            teleponField.setText("");

        } else {
            JOptionPane.showMessageDialog(this,
                    "Gagal mengubah data pelanggan karena terjadi kesalahan database.");
        }

    } catch (IllegalArgumentException e) {

        JOptionPane.showMessageDialog(this,
                e.getMessage(),
                "Validasi Input",
                JOptionPane.WARNING_MESSAGE);
    }
}

private void hapusPelanggan() {

    int baris = jTable1.getSelectedRow();

    if (baris == -1) {
        JOptionPane.showMessageDialog(this,
                "Pilih pelanggan terlebih dahulu!");
        return;
    }

    int id = Integer.parseInt(
            jTable1.getValueAt(baris, 0).toString());

    int konfirmasi = JOptionPane.showConfirmDialog(
            this,
            "Apakah Anda yakin ingin menghapus pelanggan ini?",
            "Konfirmasi Hapus",
            JOptionPane.YES_NO_OPTION
    );

    if (konfirmasi == JOptionPane.YES_OPTION) {

        if (controller.hapus(id)) {

            JOptionPane.showMessageDialog(this,
                    "Data pelanggan berhasil dihapus!");

            muatTabel();

            namaField.setText("");
            teleponField.setText("");

        } else {
            JOptionPane.showMessageDialog(this,
                    "Gagal menghapus data pelanggan!");
        }
    }
}
